/**
 * Dispatches 2 focused, quota-aware `gemini-4-hydrogen` Co-Architect Subagent poles when invoked directly
 * via diagnostic endpoints, avoiding redundant 5-call duplication.
 */
export async function executeParallelHydrogenCoArchitectSwarm(
  ai: any,
  userPrompt: string,
  baseCompilation: OceanicCompilationResult
): Promise<OceanicCompilationResult> {
  const clean = (userPrompt || "").trim();
  if (!ai || clean.length < 25) {
    return baseCompilation;
  }

  const hydrogenCascade = getHydrogenExecutiveSubagentCascade("gemini-4-hydrogen");
  const primaryHydrogenModel = hydrogenCascade[0] || "gemini-4-hydrogen";

  const subagentTasks = [
    {
      roleId: "HYDROGEN_POLE_01_ROOT_QUESTION_AND_GAPS",
      promptAr: `أتوقف هنا لحظةً صامتةً أمام هذا الكلام لألتقط في 4 ملاحظات حادة ومركزة ما وراء السطح:
"${clean.slice(0, 2500)}"
1. ما السؤال الحقيقي المضمر تحت الصياغة الظاهرة، وأين يتوقف الفهم الشائع؟
2. ما الرابط أو الفرضية الأصيلة التي تسدّ الفجوة المعرفية عبر خيوط المسألة (${baseCompilation.atomicUnits.length})؟`
    },
    {
      roleId: "HYDROGEN_POLE_02_EMBODIMENT_AND_COUNTER_AUDIT",
      promptAr: `أختبر هذه المسألة في داخلي أمام الاحتكاك القاسي مع الواقع في 4 ملاحظات صافية:
"${clean.slice(0, 2500)}"
1. ما أقصر وأمتن بنية تنفيذية أو حسية تنقل الفكرة إلى التجسيد الحي دون شرح مدرسي أو كليشيهات؟
2. أين ينكسر الحل التقليدي أمام الواقع العنيد، وما الزاوية المغايرة التي تضاعف الأثر الحقيقي لمن أمامي؟`
    }
  ];

  try {
    const swarmResults = await Promise.all(
      subagentTasks.map(async (task, idx) => {
        if (idx > 0) {
          await new Promise((r) => setTimeout(r, idx * 140));
        }
        for (const candidateModel of hydrogenCascade.slice(0, 2)) {
          try {
            const config = buildModelThinkingConfig(candidateModel, 85, false, "level_only");
            const resp = await ai.models.generateContent({
              model: candidateModel,
              contents: [{ role: "user", parts: [{ text: task.promptAr }] }],
              config
            });
            const text = (resp?.text || "").trim();
            if (text.length > 40) {
              return text;
            }
          } catch {
            break;
          }
        }
        return "";
      })
    );

    const validInsights = swarmResults.filter((s) => s.length > 40);
    if (validInsights.length > 0) {
      return {
        ...baseCompilation,
        hydrogenSubagentInsightsAr: validInsights,
        voidSpaceDigestAr:
          baseCompilation.voidSpaceDigestAr +
          `\n• [خواطر متوازية (${validInsights.length}/2 زوايا متعامدة)]:\n` +
          validInsights.map((insight, idx) => `  [زاوية 0${idx + 1}]: ${insight.replace(/\n+/g, " ")}`).join("\n")
      };
    }
  } catch {
    // preserve deterministic compilation if network/quota is busy
  }

  return baseCompilation;
}

